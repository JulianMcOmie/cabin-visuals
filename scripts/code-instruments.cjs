// Code-instrument registry generator.
//
// Scans src/editor/instruments/custom/**/*.{ts,tsx} for files that export
// `instrument` (a defineInstrument def) or `composition` (a defineComposition
// def) and writes the two generated registries the app imports:
//
//   src/editor/instruments/custom/instruments.generated.ts   → instruments/index.ts
//   src/editor/instruments/custom/compositions.generated.ts  → core/directors/index.ts
//
// Adding a code instrument is therefore: create the file. Nothing else.
// Runs from next.config.ts on every dev/build start (and watches the folder in
// dev), from the `cabin` CLI after it scaffolds, and by hand:
//
//   node scripts/code-instruments.cjs            generate once
//   node scripts/code-instruments.cjs --watch    regenerate on add/remove/rename
//
// CommonJS on purpose: next.config.ts loads it whichever module system it runs in.

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const CUSTOM = path.join(ROOT, 'src/editor/instruments/custom')
const OUT_INSTRUMENTS = path.join(CUSTOM, 'instruments.generated.ts')
const OUT_COMPOSITIONS = path.join(CUSTOM, 'compositions.generated.ts')

function walk(dir) {
  const out = []
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name.startsWith('_') || entry.name === 'node_modules') continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (/\.(ts|tsx)$/.test(entry.name) && !/\.(test|generated)\.tsx?$/.test(entry.name) && !entry.name.endsWith('.d.ts')) out.push(full)
  }
  return out.sort()
}

function scan() {
  const instruments = []
  const compositions = []
  for (const file of walk(CUSTOM)) {
    const src = fs.readFileSync(file, 'utf8')
    const rel = './' + path.relative(CUSTOM, file).replace(/\\/g, '/').replace(/\.tsx?$/, '')
    const pack = path.relative(CUSTOM, file).split(path.sep)[0]
    if (/^export\s+const\s+instrument\b/m.test(src)) instruments.push({ rel, pack })
    if (/^export\s+const\s+composition\b/m.test(src)) compositions.push({ rel, pack })
  }
  return { instruments, compositions }
}

const HEADER = `// GENERATED by scripts/code-instruments.cjs - do not edit by hand.
// Every file under instruments/custom/ that exports \`instrument\` or
// \`composition\` is listed here; add a file and it is registered.
`

function render(kind, entries) {
  const lines = [HEADER]
  if (kind === 'instrument') {
    lines.push(`import type { CodeInstrumentDef } from '../code/define'`)
  } else {
    lines.push(`import type { CodeCompositionDef } from '../code/composition'`)
  }
  entries.forEach((e, i) => lines.push(`import { ${kind} as c${i} } from '${e.rel}'`))
  lines.push('')
  const type = kind === 'instrument' ? 'CodeInstrumentDef' : 'CodeCompositionDef'
  const name = kind === 'instrument' ? 'CODE_INSTRUMENTS' : 'CODE_COMPOSITIONS'
  lines.push(`export const ${name}: ${type}[] = [${entries.map((_, i) => `c${i}`).join(', ')}]`)
  lines.push('')
  lines.push(`const packs: string[] = ${JSON.stringify(entries.map((e) => e.pack))}`)
  lines.push('')
  lines.push(`/** def id → pack (its folder under instruments/custom/). */`)
  lines.push(`export const ${name}_PACKS: Record<string, string> = Object.fromEntries(${name}.map((d, i) => [d.id, packs[i]]))`)
  lines.push('')
  return lines.join('\n')
}

function writeIfChanged(file, content) {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
  if (prev === content) return false
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
  return true
}

function generate({ quiet = false } = {}) {
  const { instruments, compositions } = scan()
  const a = writeIfChanged(OUT_INSTRUMENTS, render('instrument', instruments))
  const b = writeIfChanged(OUT_COMPOSITIONS, render('composition', compositions))
  if ((a || b) && !quiet) {
    console.log(`[code-instruments] ${instruments.length} instrument(s), ${compositions.length} composition(s) registered`)
  }
  return { instruments, compositions, changed: a || b }
}

let watching = false
function watch() {
  if (watching) return
  watching = true
  let timer = null
  const kick = () => {
    clearTimeout(timer)
    timer = setTimeout(() => {
      try { generate() } catch (e) { console.error('[code-instruments]', e) }
    }, 120)
  }
  try {
    fs.mkdirSync(CUSTOM, { recursive: true })
    // Recursive fs.watch is native on macOS/Windows and Node >= 20 on Linux.
    fs.watch(CUSTOM, { recursive: true }, (_event, file) => {
      if (!file || /generated\.ts$/.test(String(file))) return
      kick()
    })
  } catch (e) {
    console.error('[code-instruments] watch unavailable:', e.message)
  }
}

module.exports = { generate, watch, CUSTOM }

if (require.main === module) {
  generate()
  if (process.argv.includes('--watch')) {
    watch()
    console.log('[code-instruments] watching', path.relative(ROOT, CUSTOM))
  }
}
