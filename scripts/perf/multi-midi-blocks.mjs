import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const output = 'artifacts/multi-midi'
mkdirSync(output, { recursive: true })
try {
  await page.goto(process.env.MIDI_EDITOR_URL ?? 'http://localhost:3199/editor')
  await page.waitForFunction(() => !!window.__cabinStores)
  await page.evaluate(() => {
    const p = window.__cabinStores.project.getState()
    for (const id of [...p.rootTrackIds]) p.deleteTrack(id)
    const note = (id, startBeat, pitch) => ({ id, startBeat, pitch, durationBeats: 1, velocity: 90 })
    p.addTrack({ id: 'notes', name: 'Notes', type: 'base', instrumentId: 'cube', color: '#38bdf8', muted: false, solo: false, childIds: [], blocks: [
      { id: 'clip-a', startBar: 0, durationBars: 2, loop: false, notes: [note('note-a', .5, 60)] },
      { id: 'clip-b', startBar: 3, durationBars: 2, loop: true, loopLengthBars: 1, notes: [note('note-b', 1, 64)] },
    ] })
    p.addTrack({ id: 'accent', name: 'Accent', type: 'base', instrumentId: 'cube', color: '#f472b6', muted: false, solo: false, childIds: [], blocks: [
      { id: 'clip-c', startBar: 1, durationBars: 1, loop: false, notes: [note('note-c', 2, 67)] },
    ] })
    window.__cabinStores.ui.getState().setMidiPixelsPerBeat(32)
  })
  await page.locator('[data-block-id="clip-a"]').click({ position: { x: 40, y: 24 } })
  await page.locator('[data-block-id="clip-b"]').click({ modifiers: ['Shift'], position: { x: 40, y: 24 } })
  await page.locator('[data-block-id="clip-c"]').click({ modifiers: ['Meta'], position: { x: 30, y: 24 } })
  const selected = await page.evaluate(() => [...window.__cabinStores.ui.getState().selectedBlockIds].sort())
  assert.deepEqual(selected, ['clip-a', 'clip-b', 'clip-c'])
  await page.locator('[data-block-id="clip-a"]').dblclick({ position: { x: 40, y: 24 } })
  await page.waitForSelector('[data-midi-block-headers]')
  assert.equal(await page.locator('[data-midi-clip-header]').count(), 3)
  assert.equal(await page.locator('[data-midi-block-region]').count(), 3)
  assert.equal(await page.locator('[data-midi-context-note="note-b"]').count(), 2)
  assert.equal(await page.locator('[data-midi-context-note="note-c"]').count(), 1)
  await page.locator('select[title="Grid resolution"]').selectOption('0.5')
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${output}/multiple-blocks.png` })
  const originalNotes = await page.evaluate(() => JSON.stringify(Object.values(window.__cabinStores.project.getState().tracks).flatMap(t => t.blocks)))
  await page.locator('[data-midi-context-note="note-c"]').click({ button: 'right' })
  await page.waitForFunction(() => window.__cabinStores.ui.getState().editingBlock.blockId === 'clip-c')
  assert.equal(await page.evaluate(() => JSON.stringify(Object.values(window.__cabinStores.project.getState().tracks).flatMap(t => t.blocks))), originalNotes)
  await page.locator('[data-midi-clip-header="clip-a"]').click()
  const positions = await page.locator('[data-midi-clip-header]').evaluateAll(nodes => nodes.map(node => ({ id: node.dataset.midiClipHeader, x: node.offsetLeft, y: node.offsetTop })))
  assert.notEqual(positions.find(n => n.id === 'clip-a').y, positions.find(n => n.id === 'clip-c').y)
  const scroll = await page.locator('[data-midi-scroll]').evaluate(el => { el.scrollLeft = 70; return { left: el.scrollLeft, top: el.scrollTop } })
  await page.waitForTimeout(100)
  await page.locator('[data-midi-clip-header="clip-b"]').click()
  await page.waitForSelector('[data-note-id="note-b"]')
  assert.equal(await page.locator('[data-midi-clip-header]').count(), 3)
  assert.equal(await page.locator('[data-midi-context-note="note-a"]').count(), 1)
  assert.equal(await page.locator('select[title="Grid resolution"]').inputValue(), '0.5')
  const afterSwitch = await page.locator('[data-midi-scroll]').evaluate(el => ({ left: el.scrollLeft, top: el.scrollTop }))
  assert.ok(Math.abs(scroll.left - afterSwitch.left) < 1)
  await page.locator('[data-note-id="note-b"]').scrollIntoViewIfNeeded()
  const before = await page.evaluate(() => JSON.stringify(window.__cabinStores.project.getState().tracks.notes.blocks[0]))
  // Delete only the active clip's note, then undo through the normal app shortcut.
  await page.locator('[data-note-id="note-b"]').click({ position: { x: 15, y: 8 } })
  await page.keyboard.press('Delete')
  assert.equal(await page.evaluate(() => window.__cabinStores.project.getState().tracks.notes.blocks[1].notes.length), 0)
  assert.equal(await page.evaluate(() => JSON.stringify(window.__cabinStores.project.getState().tracks.notes.blocks[0])), before)
  await page.keyboard.press('Meta+z')
  await page.waitForSelector('[data-note-id="note-b"]')
  assert.equal(await page.evaluate(() => window.__cabinStores.project.getState().tracks.notes.blocks[1].notes[0].startBeat), 1)
  await page.screenshot({ path: `${output}/active-block.png` })
  const header = await page.locator('[data-midi-clip-header="clip-b"]').boundingBox()
  await page.mouse.move(header.x + 60, header.y + 12)
  await page.mouse.down()
  await page.mouse.move(header.x + 60 + 128, header.y + 12, { steps: 1 })
  await page.mouse.up()
  assert.equal(await page.evaluate(() => window.__cabinStores.project.getState().tracks.notes.blocks[1].startBar), 4)
  assert.equal(await page.evaluate(() => window.__cabinStores.project.getState().tracks.notes.blocks[0].startBar), 0)
  await page.keyboard.press('Meta+z')
  assert.equal(await page.evaluate(() => window.__cabinStores.project.getState().tracks.notes.blocks[1].startBar), 3)

  // Removing the active clip keeps remaining selected blocks open.
  await page.evaluate(() => window.__cabinStores.project.getState().deleteBlocks(new Set(['clip-b'])))
  await page.waitForFunction(() => window.__cabinStores.ui.getState().editingBlock?.blockId === 'clip-a')
  assert.equal(await page.locator('[data-midi-clip-header]').count(), 2)
  await page.locator('[data-midi-close]').click()
  await page.waitForFunction(() => window.__cabinStores.ui.getState().editingBlock === null)
  assert.deepEqual(await page.evaluate(() => window.__cabinStores.ui.getState().editingBlocks), [])
  assert.deepEqual(errors, [])
  writeFileSync(`${output}/results.json`, JSON.stringify({ selected, positions, scroll, afterSwitch, errors, passed: true }, null, 2))
  console.log('Multi-block selection, separate boundaries, loops, focus, edit isolation, undo, deletion, and close pass.')
} finally { await browser.close() }
